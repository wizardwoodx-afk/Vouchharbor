export const FEDERATION_BATCH_SIZE = 200;

/** Composition, self-proving — the number on screen is the number in code. */
export interface FederationStats {
  readonly total: number;
  readonly byDomain: Readonly<Record<string, number>>;
  readonly byStation: Readonly<Record<MissionStation, number>>;
  readonly byRiskTier: Readonly<Record<RiskTier, number>>;
  readonly byProvenance: Readonly<Record<string, number>>;
  readonly statement: string;
}

/**
 * Composition, self-proving — the number on screen is the number in code.
 *
 * The default batch is counted once and the result frozen: the panel asks for
 * these numbers on every render and the batch cannot change at runtime, so
 * re-walking 200 records to print the same 40 domains is work with no result.
 * A caller passing its own slice gets a fresh, unfrozen count — the memo is
 * keyed to the module's own data and never guesses about someone else's.
 */
export function federationStats(batch?: readonly FederationSpecialist[]): FederationStats {
  if (batch === undefined || batch === FEDERATION_BATCH) {
    if (DEFAULT_STATS === undefined) DEFAULT_STATS = deepFreeze(countBatch(FEDERATION_BATCH));
    return DEFAULT_STATS;
  }
  return countBatch(batch);
}

let DEFAULT_STATS: FederationStats | undefined;

function deepFreeze<T>(value: T): T {
  if (value !== null && typeof value === 'object') {
    for (const inner of Object.values(value as Record<string, unknown>)) deepFreeze(inner);
    Object.freeze(value);
  }
  return value;
}

function countBatch(batch: readonly FederationSpecialist[]): FederationStats {
  const byDomain: Record<string, number> = {};
  const byStation: Record<MissionStation, number> = { triage: 0, research: 0, execution: 0, verification: 0, ledger: 0 };
  const byRiskTier: Record<RiskTier, number> = { safe: 0, standard: 0, elevated: 0, regulated: 0 };
  const byProvenance: Record<string, number> = {};
  for (const s of batch) {
    byDomain[s.domain] = (byDomain[s.domain] ?? 0) + 1;
    byStation[s.station] += 1;
    byRiskTier[s.riskTier] += 1;
    byProvenance[s.provenance] = (byProvenance[s.provenance] ?? 0) + 1;
  }
  return {
    total: batch.length,
    byDomain,
    byStation,
    byRiskTier,
    byProvenance,
    statement: `${batch.length} specialists across ${Object.keys(byDomain).length} domains and 5 mission stations.`,
  };
}

/** The chain a cross-user request walks, in order. Consumed by the Bridge panel. */
export const MISSION_STATION_ORDER: readonly MissionStation[] = ['triage', 'research', 'execution', 'verification', 'ledger'];
