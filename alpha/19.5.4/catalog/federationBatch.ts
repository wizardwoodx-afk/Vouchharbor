/**
 * federationBatch.ts — 200 specialists added in 19.5.4 (Alpha).
 *
 * WHY THIS BATCH EXISTS. Vouch Harbor's differentiator is that one user's agent
 * works directly with another user's agent. A bridge is only useful if the far
 * side has real depth to call on: the crossing has to land on a specialist who
 * knows the domain, not on a generalist improvising. So the fleet grows by
 * breadth — 40 domains × the five stations of the mission cycle — and every new
 * specialist declares the same maturity contract the existing fleet holds.
 *
 * ALIGNMENT, NOT ACCRETION. Each station hands to the next (triage → research →
 * execution → verification → ledger), which mirrors the engine's own cycle, so a
 * cross-user request can enter at any station and still travel a defined path.
 * Every entry is tagged provenance: 'federation-batch', so the count on screen is
 * the count in code, and `catalogStats().byProvenance` can prove it.
 *
 * Additive data module. Nothing here changes how routing, gating or receipts work.
 */

export type RiskTier = 'safe' | 'standard' | 'elevated' | 'regulated';

/**
 * The tier a station's work carries, before the domain raises it. The station
 * sets the floor because the *work* is what a gate sees: reading and recording
 * are safe, executing is not — whichever vertical it happens in. A regulated
 * domain then raises the floor of the stations that touch it.
 */
export function riskForStation(station: MissionStation, domainTier: RiskTier): RiskTier {
  if (station === 'triage' || station === 'ledger') return 'safe';
  if (station === 'research') return 'standard';
  if (station === 'execution') return domainTier === 'regulated' ? 'regulated' : 'elevated';
  return domainTier === 'regulated' ? 'elevated' : 'standard';
}
export type MissionStation = 'triage' | 'research' | 'execution' | 'verification' | 'ledger';
export type BridgeCapabilityName =
  | 'summarise' | 'research' | 'analyse' | 'draft' | 'review'
  | 'verify' | 'translate' | 'extract' | 'plan' | 'simulate';

export interface FederationSpecialist {
  readonly id: string;
  readonly name: string;
  readonly domain: string;
  readonly category: string;
  readonly station: MissionStation;
  readonly doctrine: string;
  readonly riskTier: RiskTier;
  readonly capabilities: readonly BridgeCapabilityName[];
  /** The station this one hands to. 'none' ends the chain at the ledger. */
  readonly handsTo: MissionStation | 'none';
  readonly provenance: 'federation-batch';
}

